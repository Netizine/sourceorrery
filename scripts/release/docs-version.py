#!/usr/bin/env python3
"""Stamp the release version into the install documentation.

    python scripts/release/docs-version.py                  # stamp
    python scripts/release/docs-version.py --check          # verify only (CI)
    python scripts/release/docs-version.py --check --expect 0.3.0   # a release run

Requires Python 3.11 or later. One source decides what the install
documentation names: the workspace version in `Cargo.toml`, which
`set-version.py` keeps (`--keep-node-links` for a repository bump). Whether
that version is released comes from `CHANGELOG.md`: it is when a
`## [X.Y.Z] - YYYY-MM-DD` heading names it.

In every file of `STAMPED`, each occurrence of a SourceOrrery version (a
version a CHANGELOG heading names, or the workspace version) becomes the
workspace version: download links, tags, package versions and labels alike.
These pages name only that version, so a page that must name another
release (a transition guide, the release history) is not in the list, and
a third-party version in a listed page must not equal a SourceOrrery
release.

Each file of `NOTED` also carries one generated block between the markers
below. While the workspace version is not released, the block says so
and links to building that source version; once the
CHANGELOG names the version, the block is empty. The bindings' READMEs are
the registries' package pages, published only at a release, and carry no
block.

`--check` changes nothing and fails on any page that stamping would change.
`--expect VERSION` also requires the workspace version to be VERSION and
released: the documentation of a release names it and no other.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILDING = "docs/building.md"
SITE_BUILDING = "/guides/building-from-source/"

# Pages that carry the release note and the version.
NOTED = (
    "README.md",
    "docs/building.md",
    "docs/supply-chain.md",
    "docs/ai-agents.md",
    "docs/sdks/index.md",
    "docs/sdks/python.md",
    "docs/sdks/javascript.md",
    "docs/sdks/rust.md",
    "docs/sdks/java.md",
    "docs/sdks/dotnet.md",
    "docs/sdks/go.md",
    "docs/sdks/c.md",
    "docs/sdks/cpp.md",
    "docs/sdks/php.md",
    "site/src/content/docs/getting-started.mdx",
    "site/src/content/docs/index.mdx",
)
# Pages that carry the version only.
VERSION_ONLY = (
    "crates/sourceorrery-cli/README.md",
    "crates/sourceorrery/README.md",
    "crates/sourceorrery-core/README.md",
    "crates/sourceorrery-crypto/README.md",
    "crates/sourceorrery-storage/README.md",
    "crates/sourceorrery-provider/README.md",
    "crates/sourceorrery-provider-vault/README.md",
    "crates/sourceorrery-provider-aws/README.md",
    "crates/sourceorrery-provider-azure/README.md",
    "crates/sourceorrery-ffi/README.md",
    "crates/sourceorrery-os/README.md",
    "scripts/release/ffi-archive-README.md",
    "docs/README.md",
    "docs/architecture.md",
    "docs/cli.md",
    "docs/roadmap.md",
    "docs/upgrading.md",
    "docs/security-review.md",
    "docs/coverage.md",
    "bindings/README.md",
    "bindings/cpp/README.md",
    "bindings/dotnet/README.md",
    "bindings/go/README.md",
    "bindings/java/README.md",
    "bindings/node/README.md",
    "bindings/php/README.md",
    "bindings/python/README.md",
    "bindings/node/npm/darwin-arm64/README.md",
    "bindings/node/npm/darwin-x64/README.md",
    "bindings/node/npm/linux-arm64-gnu/README.md",
    "bindings/node/npm/linux-x64-gnu/README.md",
    "bindings/node/npm/win32-arm64-msvc/README.md",
    "bindings/node/npm/win32-x64-msvc/README.md",
    "site/README.md",
)
STAMPED = NOTED + VERSION_ONLY

SEMVER = r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?"
HEADING = re.compile(rf"^## \[({SEMVER})\] - \d{{4}}-\d{{2}}-\d{{2}}\s*$", re.MULTILINE)
MARKERS = {
    ".md": ("<!-- release-note: generated by scripts/release/docs-version.py -->", "<!-- /release-note -->"),
    ".mdx": ("{/* release-note: generated by scripts/release/docs-version.py */}", "{/* /release-note */}"),
}


class Problem(Exception):
    """The documentation cannot be stamped or does not match; the message says why."""


def tokens(known: set[str]) -> re.Pattern[str]:
    """The known versions, each not part of a longer dotted number: `v0.3.0`,
    `-0.3.0-`, `SourceOrrery.0.3.0.nupkg` and `0.3.0.` at the end of a
    sentence are versions; `1.0.3.0`, `0.3.0.1` and `0.3.01` are not."""
    alternatives = "|".join(re.escape(v) for v in sorted(known, key=len, reverse=True))
    return re.compile(rf"(?<!\d)(?<!\d\.)(?:{alternatives})(?!\d|\.\d)")


def key(version: str) -> tuple:
    core, _, pre = version.partition("-")
    major, minor, patch = (int(part) for part in core.split("."))
    # A prerelease sorts before its release.
    return (major, minor, patch, pre == "", pre)


def workspace_version(root: Path) -> str:
    cargo = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8"))
    version = cargo["workspace"]["package"]["version"]
    if not re.fullmatch(SEMVER, version):
        raise Problem(f"Cargo.toml: workspace version '{version}' is not a semantic version")
    return version


def releases(root: Path) -> list[str]:
    """The released versions CHANGELOG.md names, newest first."""
    found = HEADING.findall((root / "CHANGELOG.md").read_text(encoding="utf-8"))
    if not found:
        raise Problem("CHANGELOG.md names no release (`## [X.Y.Z] - YYYY-MM-DD`)")
    return sorted(set(found), key=key, reverse=True)


def note(path: str, version: str) -> str:
    """The release note for `path` while `version` is not released."""
    if path.startswith("site/"):
        building = SITE_BUILDING
    else:
        building = Path(os.path.relpath(ROOT / BUILDING, (ROOT / path).parent)).as_posix()
    body = (
        f"These pages describe the {version} source tree. Versioned packages and "
        f"release downloads become available when that version is published. "
        f"To try this build before publication, [build from source]({building})."
    )
    title = f"SourceOrrery {version} is not released yet"
    if path.endswith(".mdx"):
        return f'<Aside type="caution" title="{title}">\n{body}\n</Aside>'
    return f"> [!IMPORTANT]\n> **{title}.** {body}"


def stamp_text(path: str, text: str, version: str, known: set[str], released: list[str]) -> str:
    """`text` with every SourceOrrery version set to `version` and its note current."""
    marked = path in NOTED
    start, end = MARKERS[Path(path).suffix]
    pieces = text.split(start)
    if marked and len(pieces) != 2:
        raise Problem(f"{path}: needs exactly one `{start}` ... `{end}` block (it has {len(pieces) - 1})")
    if not marked and len(pieces) != 1:
        raise Problem(f"{path}: carries a release note but is not in NOTED")

    pattern = tokens(known)

    def versions(chunk: str) -> str:
        return pattern.sub(version, chunk)

    if not marked:
        return versions(text)
    before, rest = pieces
    if rest.count(end) != 1:
        raise Problem(f"{path}: the release note opened by `{start}` is not closed by `{end}`")
    _, after = rest.split(end)
    block = "" if version in released else note(path, version) + "\n"
    return f"{versions(before)}{start}\n{block}{end}{versions(after)}"


def plan(root: Path = ROOT) -> tuple[str, bool, dict[str, tuple[str, str]]]:
    """The workspace version, whether it is released, and each file's text before and after."""
    version = workspace_version(root)
    released = releases(root)
    if version not in released and key(version) < key(released[0]):
        raise Problem(
            f"the workspace version {version} is older than the latest release {released[0]} "
            "(CHANGELOG.md); bump it with set-version.py --keep-node-links"
        )
    known = set(released) | {version}
    changes = {}
    for path in STAMPED:
        file = root / path
        if not file.is_file():
            raise Problem(f"{path} is listed in docs-version.py but does not exist")
        text = file.read_text(encoding="utf-8")
        changes[path] = (text, stamp_text(path, text, version, known, released))
    return version, version in released, changes


def stale_lines(before: str, after: str) -> list[int]:
    a, b = before.splitlines(), after.splitlines()
    return [n + 1 for n, (x, y) in enumerate(zip(a, b)) if x != y] or [min(len(a), len(b)) + 1]


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify only")
    parser.add_argument("--expect", metavar="VERSION", help="with --check: the released version the docs must name")
    args = parser.parse_args(argv)
    if args.expect and not args.check:
        parser.error("--expect goes with --check")
    try:
        version, is_released, changes = plan(root)
    except Problem as problem:
        print(f"docs-version: {problem}", file=sys.stderr)
        return 1
    stale = {path: pair for path, pair in changes.items() if pair[0] != pair[1]}
    if args.check:
        failed = False
        for path, (before, after) in stale.items():
            lines = ", ".join(str(n) for n in stale_lines(before, after)[:8])
            print(f"docs-version: {path} does not match version {version} (line {lines})")
            failed = True
        if args.expect and (args.expect != version or not is_released):
            print(
                f"docs-version: the documentation names {version} "
                f"({'released' if is_released else 'not released in CHANGELOG.md'}), not the release {args.expect}"
            )
            failed = True
        if failed:
            print("docs-version: run `python scripts/release/docs-version.py` and commit the result")
            return 1
        state = "released" if is_released else "not released yet; the pages say so"
        print(f"docs-version: {len(changes)} pages name {version} ({state})")
        return 0
    for path, (_, after) in stale.items():
        (root / path).write_text(after, encoding="utf-8", newline="\n")
        print(f"docs-version: updated {path}")
    if not stale:
        print(f"docs-version: every page already names {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
