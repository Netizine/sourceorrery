#!/usr/bin/env python3
"""Render the package-manager manifests for one release.

From a version and the release's ``SHA256SUMS`` this writes:

* ``homebrew/Formula/sourceorrery.rb`` for the tap
  ``Netizine/homebrew-sourceorrery`` (macOS and Linux, x64 and arm64),
* ``scoop/bucket/sourceorrery.json`` for the bucket
  ``Netizine/scoop-sourceorrery`` (Windows x64 and arm64), and
* ``winget/manifests/n/Netizine/SourceOrrery/<version>/*.yaml``, the three
  WinGet manifests ``wingetcreate submit`` sends to ``microsoft/winget-pkgs``.

Every URL points at the GitHub Release and every hash comes from its
``SHA256SUMS``, so what a package manager installs is byte for byte the
release archive. The release workflow runs this after the release exists;
``scripts/release/package_managers_test.py`` checks the output.

    python3 scripts/release/package-managers.py --version 0.2.0 \\
        --sha256sums SHA256SUMS --release-date 2026-10-23 --out dist/package-managers

``--sha256sums`` and ``--out`` must lie under the working directory.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

REPO = "Netizine/sourceorrery"
HOMEPAGE = "https://sourceorrery.ai"
DESCRIPTION = (
    "Encrypted local secrets vault with a cloud-secrets-manager-style lifecycle API"
)
WINGET_ID = "Netizine.SourceOrrery"
WINGET_MANIFEST_VERSION = "1.12.0"


def under_working_directory(path: Path, what: str) -> Path:
    """``path`` resolved, once it is known to lie under the working directory.

    The script reads and writes only inside the checkout it runs in, so an
    argument cannot point it at another file.
    """
    root = os.path.realpath(os.getcwd())
    resolved = os.path.realpath(path)
    if resolved != root and not resolved.startswith(root + os.sep):
        raise ValueError(f"{what} must be under the working directory: {path}")
    return Path(resolved)

# target triple -> (Homebrew os, Homebrew arch) / Scoop and WinGet architecture
BREW_TARGETS = {
    "aarch64-apple-darwin": ("macos", "arm"),
    "x86_64-apple-darwin": ("macos", "intel"),
    "aarch64-unknown-linux-gnu": ("linux", "arm"),
    "x86_64-unknown-linux-gnu": ("linux", "intel"),
}
WINDOWS_TARGETS = {
    "x86_64-pc-windows-msvc": ("64bit", "x64"),
    "aarch64-pc-windows-msvc": ("arm64", "arm64"),
}

SEMVER = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$")


class RenderError(Exception):
    """A manifest cannot be rendered from this input."""


def parse_sha256sums(text: str) -> dict[str, str]:
    """``sha256sum`` output -> {file name: lowercase hex digest}."""
    sums: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split(maxsplit=1)
        if len(parts) != 2 or not re.fullmatch(r"[0-9a-fA-F]{64}", parts[0]):
            raise RenderError(f"malformed SHA256SUMS line: {line!r}")
        name = parts[1].lstrip("*")
        if name in sums:
            raise RenderError(f"SHA256SUMS names {name} twice")
        sums[name] = parts[0].lower()
    return sums


def release_url(version: str, file: str, repo: str = REPO) -> str:
    return f"https://github.com/{repo}/releases/download/v{version}/{file}"


def cli_archive(version: str, target: str) -> str:
    ext = "zip" if target.endswith("-windows-msvc") else "tar.gz"
    return f"sourceorrery-{version}-{target}.{ext}"


def digest(sums: dict[str, str], file: str) -> str:
    try:
        return sums[file]
    except KeyError:
        raise RenderError(f"SHA256SUMS has no entry for {file}") from None


def render_formula(version: str, sums: dict[str, str], repo: str = REPO) -> str:
    def block(os_name: str) -> str:
        lines = [f"  on_{os_name} do"]
        for target, (os_, arch) in BREW_TARGETS.items():
            if os_ != os_name:
                continue
            file = cli_archive(version, target)
            lines += [
                f"    on_{arch} do",
                f'      url "{release_url(version, file, repo)}"',
                f'      sha256 "{digest(sums, file)}"',
                "    end",
            ]
        lines.append("  end")
        return "\n".join(lines)

    return f"""# Generated by scripts/release/package-managers.py in {repo}; do not edit.
class Sourceorrery < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license any_of: ["MIT", "Apache-2.0"]

{block("macos")}

{block("linux")}

  def install
    bin.install "sourceorrery"
    generate_completions_from_executable(bin/"sourceorrery", "completions")
  end

  test do
    assert_match "sourceorrery #{{version}}", shell_output("#{{bin}}/sourceorrery --version")
  end
end
"""


def render_scoop(version: str, sums: dict[str, str], repo: str = REPO) -> str:
    arch: dict[str, dict[str, str]] = {}
    autoupdate_arch: dict[str, dict[str, str]] = {}
    for target, (scoop_arch, _) in WINDOWS_TARGETS.items():
        file = cli_archive(version, target)
        arch[scoop_arch] = {
            "url": release_url(version, file, repo),
            "hash": digest(sums, file),
        }
        autoupdate_arch[scoop_arch] = {
            "url": release_url("$version", cli_archive("$version", target), repo)
        }
    manifest = {
        "version": version,
        "description": DESCRIPTION,
        "homepage": HOMEPAGE,
        "license": "MIT|Apache-2.0",
        "architecture": arch,
        "bin": "sourceorrery.exe",
        "checkver": {"github": f"https://github.com/{repo}"},
        "autoupdate": {
            "architecture": autoupdate_arch,
            "hash": {"url": "$baseurl/SHA256SUMS"},
        },
    }
    return json.dumps(manifest, indent=4) + "\n"


def render_winget(version: str, sums: dict[str, str], repo: str = REPO) -> dict[str, str]:
    """The three WinGet manifests, keyed by file name."""
    head = f"PackageIdentifier: {WINGET_ID}\nPackageVersion: {version}\n"
    tail = f"ManifestVersion: {WINGET_MANIFEST_VERSION}\n"
    schema = "# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.{v}.schema.json\n"

    version_yaml = (
        schema.format(kind="version", v=WINGET_MANIFEST_VERSION)
        + head
        + "DefaultLocale: en-US\nManifestType: version\n"
        + tail
    )

    installers = ""
    for target, (_, winget_arch) in WINDOWS_TARGETS.items():
        file = cli_archive(version, target)
        installers += (
            f"  - Architecture: {winget_arch}\n"
            f"    InstallerUrl: {release_url(version, file, repo)}\n"
            f"    InstallerSha256: {digest(sums, file).upper()}\n"
        )
    installer_yaml = (
        schema.format(kind="installer", v=WINGET_MANIFEST_VERSION)
        + head
        + "InstallerType: zip\n"
        "NestedInstallerType: portable\n"
        "NestedInstallerFiles:\n"
        "  - RelativeFilePath: sourceorrery.exe\n"
        "    PortableCommandAlias: sourceorrery\n"
        f"ReleaseDate: {{release_date}}\n"
        "Installers:\n" + installers + "ManifestType: installer\n" + tail
    )

    locale_yaml = (
        schema.format(kind="defaultLocale", v=WINGET_MANIFEST_VERSION)
        + head
        + "PackageLocale: en-US\n"
        "Publisher: Netizine\n"
        f"PublisherUrl: https://github.com/{repo.split('/')[0]}\n"
        f"PublisherSupportUrl: https://github.com/{repo}/issues\n"
        "PackageName: SourceOrrery\n"
        f"PackageUrl: {HOMEPAGE}\n"
        "License: MIT OR Apache-2.0\n"
        f"LicenseUrl: https://github.com/{repo}/blob/v{version}/LICENSE-MIT\n"
        f"ShortDescription: {DESCRIPTION}\n"
        "Description: |-\n"
        "  SourceOrrery keeps development secrets in an encrypted local vault\n"
        "  and hands them to applications through a CLI and read-only SDKs, so\n"
        "  no .env file holds a value. The CLI creates vaults and stores secrets;\n"
        "  the SDKs for Python, JavaScript, Rust, Java, .NET, Go, C, C++ and PHP\n"
        "  only read them.\n"
        "Moniker: sourceorrery\n"
        "Tags:\n"
        "  - secrets\n"
        "  - vault\n"
        "  - dotenv\n"
        "  - security\n"
        "  - cli\n"
        f"ReleaseNotesUrl: https://github.com/{repo}/releases/tag/v{version}\n"
        "Documentations:\n"
        "  - DocumentLabel: Getting started\n"
        f"    DocumentUrl: {HOMEPAGE}/getting-started/\n"
        "ManifestType: defaultLocale\n" + tail
    )
    return {
        f"{WINGET_ID}.yaml": version_yaml,
        f"{WINGET_ID}.installer.yaml": installer_yaml,
        f"{WINGET_ID}.locale.en-US.yaml": locale_yaml,
    }


def render_all(
    version: str, sums: dict[str, str], release_date: str, repo: str = REPO
) -> dict[str, str]:
    """Every output file, keyed by its path under the output directory."""
    if not SEMVER.match(version):
        raise RenderError(f"{version!r} is not a semantic version")
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", release_date):
        raise RenderError(f"{release_date!r} is not a YYYY-MM-DD date")
    files = {
        "homebrew/Formula/sourceorrery.rb": render_formula(version, sums, repo),
        "scoop/bucket/sourceorrery.json": render_scoop(version, sums, repo),
    }
    winget_dir = f"winget/manifests/n/Netizine/SourceOrrery/{version}"
    for name, text in render_winget(version, sums, repo).items():
        files[f"{winget_dir}/{name}"] = text.replace("{release_date}", release_date)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", required=True, help="release version, no v")
    parser.add_argument("--sha256sums", required=True, type=Path, help="the release's SHA256SUMS")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    parser.add_argument("--release-date", required=True, help="YYYY-MM-DD, for the WinGet manifest")
    parser.add_argument("--repo", default=REPO, help=f"GitHub repository (default {REPO})")
    args = parser.parse_args(argv)
    try:
        sums = parse_sha256sums(under_working_directory(args.sha256sums, "--sha256sums").read_text())
        out = under_working_directory(args.out, "--out")
        files = render_all(args.version, sums, args.release_date, args.repo)
    except (RenderError, ValueError, OSError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    for rel, text in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, newline="\n")
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
